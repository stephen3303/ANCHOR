import { TemplateValidationError, isCommandChoice, isDraftManagedField, type TemplateField, type TemplateValues } from "./message-templates";
import { ZULU_DATETIME_PATTERN } from "./format";

export const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
export const PRECEDENCES = ["FLASH", "IMMEDIATE", "PRIORITY", "ROUTINE"] as const;
export class MessageInputError extends TemplateValidationError {
  constructor(public fields: Record<string, string>) { super("Check the highlighted message fields."); }
}
function validDate(text: string): boolean {
  const date = new Date(`${text}T00:00:00Z`);
  return /^\d{4}-\d{2}-\d{2}$/.test(text) && !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === text;
}
function validZulu(text: string): boolean {
  if (!new RegExp(ZULU_DATETIME_PATTERN).test(text)) return false;
  const [day, month, year] = text.split(" ");
  const index = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"].indexOf(month);
  return validDate(`${year}-${String(index + 1).padStart(2, "0")}-${day}`);
}

// Validate original option labels/booleans and command IDs, never rendered
// overrides or client-supplied automatic outputs. Optional omissions become empty.
export function validateMessageInputs(fields: TemplateField[], input: unknown): TemplateValues {
  if (!input || typeof input !== "object" || Array.isArray(input)) throw new MessageInputError({ _form: "Inputs must be an object." });
  const raw = input as Record<string, unknown>;
  const errors: [string, string][] = [];
  const values: [string, string | string[] | boolean][] = [];
  for (const key of Object.keys(raw)) {
    const field = fields.find((item) => item.name === key);
    // Precedence and the release DTG are supplied by the draft, not typed; older clients may still send them.
    if (field && isDraftManagedField(field) && field.control !== "autogenerated" && field.fixedValue === undefined) continue;
    if (!field || field.control === "autogenerated" || field.fixedValue !== undefined) errors.push([key, "Unknown or server-generated field; do not supply a value."]);
  }
  for (const field of fields) {
    if (field.control === "autogenerated" || field.fixedValue !== undefined || isDraftManagedField(field)) continue;
    const multiple = field.control === "command-multiple" || field.control === "checkbox-group";
    let value = Object.hasOwn(raw, field.name) ? raw[field.name] : field.control === "checkbox" ? false : multiple ? [] : "";
    if (isCommandChoice(field.control)) {
      value = Array.isArray(value) ? value.map((id) => typeof id === "string" ? id.toLowerCase() : id) : typeof value === "string" ? value.toLowerCase() : value;
    }
    const fail = (message: string) => errors.push([field.name, message]);
    if (field.control === "checkbox") {
      if (typeof value !== "boolean") fail("Choose YES or NO.");
      else if (field.required && !value) fail("This checkbox must be checked.");
    } else if (multiple) {
      if (!Array.isArray(value) || value.length > 100 || value.some((item) => typeof item !== "string" || item.includes("\0"))) fail("Choose at most 100 valid options.");
      else if (new Set(value).size !== value.length) fail("Remove duplicate selections.");
      else if (field.required && !value.length) fail("Choose at least one option.");
      else if (field.control === "checkbox-group" && value.some((item) => !field.options.includes(item))) fail("Choose only the listed options.");
      else if (field.control === "command-multiple" && value.some((item) => !UUID_PATTERN.test(item))) fail("Choose commands from the directory.");
    } else if (typeof value !== "string" || value.length > 5000 || value.includes("\0")) fail("Enter text of at most 5,000 characters.");
    else if (field.required && !value.trim()) fail("This field is required.");
    else if (value) {
      if (["select", "radio"].includes(field.control) && !field.options.includes(value)) fail("Choose one of the listed options.");
      if (isCommandChoice(field.control) && !UUID_PATTERN.test(value)) fail("Choose a command from the directory.");
      if (field.control === "date" && !validDate(value)) fail("Enter a valid calendar date.");
      if (field.control === "datetime-local" && !validZulu(value)) fail("Enter a valid DD MMM YYYY HHMMZ date/time.");
    }
    values.push([field.name, value as string | string[] | boolean]);
  }
  if (errors.length) throw new MessageInputError(Object.fromEntries(errors));
  return Object.fromEntries(values);
}
