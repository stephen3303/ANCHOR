export const INPUT_TYPES = [
  ["text", "Textbox"], ["textarea", "Multiline text"], ["select", "Dropdown"],
  ["radio", "Radio buttons"], ["checkbox", "Checkbox (yes/no)"],
  ["checkbox-group", "Checkbox group"], ["command-single", "Command picker (single)"],
  ["command-multiple", "Command picker (multiple / TO field)"],
  ["date", "Date"], ["datetime-local", "Date and time (Zulu)"],
  ["autogenerated", "Autogenerated"],
  ["reference-list", "References (REF / AMPN / NARR)"],
] as const;
export type InputType = (typeof INPUT_TYPES)[number][0];
export const COMMAND_SEPARATORS = [
  { key: "semicolon", label: "Semicolon", value: "; " },
  { key: "space", label: "Space", value: " " },
  { key: "newline", label: "Newline", value: "\n" },
] as const;
export type CommandSeparator = (typeof COMMAND_SEPARATORS)[number]["key"];
export interface TemplateField {
  name: string;
  control: InputType;
  required: boolean;
  options: string[];
  optionOutputs?: Record<string, string>;
  generator?: GeneratorBinding;
  separator?: CommandSeparator;
  /** Author-defined constant, currently reserved for Type. */
  fixedValue?: string;
}
export interface TemplateDefinition {
  name: string;
  description: string;
  text: string;
  fields: TemplateField[];
}
export interface TemplateSummary {
  id: string;
  name: string;
  description: string;
  version: number;
  publishedAt: string;
  variableCount: number;
  canEdit?: boolean;
  /** Why this account cannot edit, shown beside the disabled Edit button. */
  editNote?: string;
  createdByName?: string | null;
}
export type TemplateValues = Record<string, string | string[] | boolean>;

// Two standard fields are never typed into the form. The draft's single
// precedence choice fills {{ Precedence }}, and {{ DateTime }} is the DTG,
// which is stamped when the Release Authority releases the message.
export const PRECEDENCE_FIELD = "Precedence";
export const RELEASE_DTG_FIELD = "DateTime";
/** Shown in the draft text until release replaces it with the DTG. Same width as a DTG. */
export const RELEASE_DTG_MARKER = "DDHHMMZ MMM YY";
/** "Message DateTime" is the older name of DateTime, still pinned by early template versions. */
const RELEASE_DTG_FIELDS = [RELEASE_DTG_FIELD, "Message DateTime"];
export const isReleaseDtgField = (field: Pick<TemplateField, "name">) => RELEASE_DTG_FIELDS.includes(field.name);
export const isDraftManagedField = (field: Pick<TemplateField, "name">) => field.name === PRECEDENCE_FIELD || isReleaseDtgField(field);
/** The template input value for a draft precedence: the option whose output (or label) starts with Z, O, P or R. */
export function precedenceInput(field: TemplateField, precedence: string): string {
  const word = precedence.trim().toUpperCase();
  const prosign = ({ FLASH: "Z", IMMEDIATE: "O", PRIORITY: "P", ROUTINE: "R" } as Record<string, string>)[word] ?? word.charAt(0);
  if (!isStaticChoice(field.control)) return prosign;
  const output = (option: string) => (field.optionOutputs?.[option]?.trim() || option).toUpperCase();
  return field.options.find((option) => output(option).startsWith(prosign)) ?? field.options.find((option) => option.toUpperCase().startsWith(prosign)) ?? prosign;
}
/** Values the server or the precedence selector supply for the managed fields. */
export function draftManagedValues(fields: readonly TemplateField[], precedence: string): TemplateValues {
  const values: TemplateValues = {};
  for (const field of fields) {
    if (field.control === "autogenerated" || field.fixedValue !== undefined) continue;
    if (field.name === PRECEDENCE_FIELD) values[field.name] = precedenceInput(field, precedence);
    if (isReleaseDtgField(field)) values[field.name] = RELEASE_DTG_MARKER;
  }
  return values;
}
/** Put the release marker back in place of the release DTG: the text the approvers approved. */
export function unstampReleaseDtg(text: string, dtg: string | undefined): string {
  if (!dtg) return text;
  const lines = text.split("\n");
  const firstBreak = lines.indexOf("BT");
  const end = firstBreak === -1 ? lines.length : firstBreak;
  for (let index = 0; index < end; index += 1) {
    if (lines[index].includes(dtg)) { lines[index] = lines[index].replace(dtg, RELEASE_DTG_MARKER); break; }
  }
  return lines.join("\n");
}
/** Replace the release marker in the message heading (before the first BT) with the release DTG. */
export function stampReleaseDtg(text: string, dtg: string): string {
  const lines = text.split("\n");
  const firstBreak = lines.indexOf("BT");
  const end = firstBreak === -1 ? lines.length : firstBreak;
  for (let index = 0; index < end; index += 1) {
    if (lines[index].includes(RELEASE_DTG_MARKER)) { lines[index] = lines[index].replace(RELEASE_DTG_MARKER, dtg); break; }
  }
  return lines.join("\n");
}

export class TemplateValidationError extends Error {}
const invalid = (message: string): never => { throw new TemplateValidationError(message); };
export const isStaticChoice = (control: InputType) => ["select", "radio", "checkbox-group"].includes(control);
export const isCommandChoice = (control: InputType) => control.startsWith("command-");
/** The longest References value: up to 26 references, each with its amplification. */
export const MAX_REFERENCE_VALUE = 100000;

/**
 * The REF, AMPN and NARR lines a References value renders to, or null when the
 * value can't be read yet (the preview then keeps the placeholder).
 */
export function renderReferenceValue(value: unknown): string | null {
  try {
    return formatDraftReferences(parseReferenceValue(value)).join("\n");
  } catch {
    return null;
  }
}

export function extractVariables(text: string): string[] {
  if (!text.trim()) invalid("Paste a plaintext template first.");
  if (text.length > 50000) invalid("Template text must be 50,000 characters or fewer.");
  if (text.includes("\0")) invalid("Template text cannot contain null characters.");
  const variables: string[] = [];
  const remaining = text.replace(/{{([^{}]*)}}/g, (_match, raw: string) => {
    const name = raw.trim();
    if (!/^[A-Za-z][A-Za-z0-9 _-]{0,63}$/.test(name)) {
      invalid('Variable names must start with a letter and contain only letters, numbers, spaces, "_", or "-" (up to 64 characters).');
    }
    if (!variables.includes(name)) variables.push(name);
    return "";
  });
  if (remaining.includes("{{") || remaining.includes("}}") || /{{{|}}}/.test(text)) {
    invalid('Unmatched or nested template braces. Use "{{ Name }}" for each variable.');
  }
  if (!variables.length) invalid('Add at least one named variable, such as "{{ Subject }}".');
  if (variables.length > 100) invalid("A template can contain at most 100 unique variables.");
  return variables;
}

function boundedString(value: unknown, label: string, max: number, required = true): string {
  if (typeof value !== "string" || value.includes("\0")) invalid(`${label} must be text without null characters.`);
  const text = (value as string).trim();
  if ((required && !text) || text.length > max) invalid(`${label} ${required ? "is required and " : ""}must be ${max} characters or fewer.`);
  return text;
}

export function validateTemplateDefinition(value: unknown): TemplateDefinition {
  if (!value || typeof value !== "object" || Array.isArray(value)) invalid("Expected a template object.");
  const input = value as Record<string, unknown>;
  const name = boundedString(input.name, "Template name", 150);
  const description = boundedString(input.description, "Description", 2000, false);
  if (typeof input.text !== "string") invalid("Template text must be plaintext.");
  const text = (input.text as string).replace(/\r\n?/g, "\n");
  const variables = extractVariables(text);
  if (!Array.isArray(input.fields) || input.fields.length !== variables.length) {
    invalid("Configure exactly one input for every detected variable.");
  }
  const seen = new Set<string>();
  let seenReferenceList = 0;
  const fields = (input.fields as unknown[]).map((item): TemplateField => {
    if (!item || typeof item !== "object" || Array.isArray(item)) invalid("Invalid variable configuration.");
    const field = item as Record<string, unknown>;
    const fieldName = boundedString(field.name, "Variable name", 64);
    if (!variables.includes(fieldName) || seen.has(fieldName)) invalid(`Unknown or duplicate variable: ${fieldName}.`);
    seen.add(fieldName);
    if (!INPUT_TYPES.some(([type]) => type === field.control)) invalid(`Choose a supported input for ${fieldName}.`);
    if (typeof field.required !== "boolean") invalid(`Specify whether ${fieldName} is required.`);
    const control = field.control as InputType;
    let fixedValue: string | undefined;
    if (field.fixedValue !== undefined) {
      // Keep historical pinned versions readable; new publications use Type.
      if (!["Type", "Msg Type"].includes(fieldName) || control !== "text" || !field.required) invalid("Type must be a required text field with an author-defined value.");
      fixedValue = boundedString(field.fixedValue, "Type value", 200);
      if (/[\r\n]/.test(fixedValue)) invalid("Type value must be a single line.");
    }
    if (!Array.isArray(field.options) || field.options.length > 100) invalid(`Options for ${fieldName} must be a list of at most 100 choices.`);
    const options = (field.options as unknown[]).map((option) => boundedString(option, `Option for ${fieldName}`, 200));
    if (isStaticChoice(control)) {
      if (!options.length) invalid(`Add at least one option for ${fieldName}.`);
      if (new Set(options).size !== options.length) invalid(`Remove duplicate options for ${fieldName}.`);
    } else if (options.length) invalid(`${fieldName} does not accept static options.`);
    let optionOutputs: Record<string, string> | undefined;
    if (field.optionOutputs !== undefined) {
      if (!isStaticChoice(control) && control !== "checkbox") invalid(`${fieldName} only accepts output overrides for choice inputs or checkboxes.`);
      if (!field.optionOutputs || typeof field.optionOutputs !== "object" || Array.isArray(field.optionOutputs)) invalid(`Output overrides for ${fieldName} must be an object.`);
      const entries = Object.entries(field.optionOutputs as Record<string, unknown>);
      const allowed = control === "checkbox" ? ["YES", "NO"] : options;
      if (entries.length > allowed.length) invalid(`Too many output overrides for ${fieldName}.`);
      const normalized: [string, string][] = [];
      for (const [label, output] of entries) {
        if (!allowed.includes(label)) invalid(`Unknown output option for ${fieldName}: ${label}.`);
        if (typeof output !== "string" || output.includes("\0") || output.length > 5000) invalid(`Output for ${fieldName}: ${label} must be text of at most 5,000 characters without null characters.`);
        // Blank means no override. Preserve meaningful whitespace/newlines in
        // nonblank replacement text; values are inserted once as plaintext.
        if ((output as string).trim()) normalized.push([label, output as string]);
      }
      if (normalized.length) optionOutputs = Object.fromEntries(normalized);
    }
    let generator: GeneratorBinding | undefined;
    if (control === "autogenerated") {
      const binding = field.generator;
      if (!binding || typeof binding !== "object" || Array.isArray(binding)) invalid(`Choose an autogenerated output for ${fieldName}.`);
      const { key, version } = binding as Record<string, unknown>;
      if (!isSupportedGenerator(key, version)) invalid(`Choose a supported autogenerated output for ${fieldName}.`);
      if (!field.required) invalid(`Autogenerated variable ${fieldName} must be required; it is supplied by the server, not the user.`);
      generator = { key: key as GeneratorBinding["key"], version: version as GeneratorBinding["version"] };
    } else if (field.generator !== undefined) invalid(`${fieldName} only accepts a generator when its input type is Autogenerated.`);
    if (control === "reference-list" && seenReferenceList++) invalid("A template can have only one References input; it holds every REF set.");
    if (field.separator !== undefined) {
      if (control !== "command-multiple") invalid(`${fieldName} only accepts a separator for a multiple-command picker.`);
      if (!COMMAND_SEPARATORS.some(({ key }) => key === field.separator)) invalid(`Choose semicolon, space, or newline separation for ${fieldName}.`);
    }
    return { name: fieldName, control, required: field.required as boolean, options, ...(fixedValue !== undefined ? { fixedValue } : {}), ...(optionOutputs ? { optionOutputs } : {}), ...(generator ? { generator } : {}), ...(field.separator !== undefined ? { separator: field.separator as CommandSeparator } : {}) };
  });
  // Stable first-occurrence order, independent of client submission order.
  return { name, description, text, fields: variables.map((variable) => fields.find((field) => field.name === variable)!) };
}

/** Publication-only checks: pinned historical definitions remain readable. */
export function validateStandardTemplateText(text: string): string[] {
  const normalized = text.replace(/\r\n?/g, "\n");
  const variables = extractVariables(normalized);
  for (const name of ["Type", ...STANDARD_FIELD_NAMES]) {
    if (!variables.includes(name)) invalid(`Every template must include {{ ${name} }} (case-sensitive).`);
  }
  for (const [oldName, name] of Object.entries(LEGACY_STANDARD_NAMES)) {
    if (variables.includes(oldName)) invalid(`Rename {{ ${oldName} }} to {{ ${name} }} before publishing.`);
  }
  const lines = normalized.trimEnd().split("\n");
  const breaks = lines.flatMap((line, index) => line === "BT" ? [index] : []);
  if (breaks.length !== 2) invalid("Every template must contain exactly two standalone plaintext BT lines.");
  if (lines.at(-1) !== "NNNN") invalid("Every template must end with a standalone plaintext NNNN line.");
  const firstLine = (name: string) => lines.findIndex((line) => [...line.matchAll(/{{([^{}]*)}}/g)].some((match) => match[1].trim() === name));
  const header = ["Precedence", "DateTime", "Origin", "Recipients", "Info"].map(firstLine);
  const body = ["Classification", "Subject", "POC"].map(firstLine);
  const number = firstLine("Message Number");
  const ordered = (positions: number[]) => positions.every((position, index) => index === 0 || position >= positions[index - 1]);
  if (!ordered(header) || header.some((line) => line >= breaks[0]) || !ordered(body) || body.some((line) => line <= breaks[0] || line >= breaks[1]) || number <= breaks[1] || number >= lines.length - 1) {
    invalid("Use standard field order: Precedence, DateTime, Origin, Recipients, Info, BT, Classification, Subject, POC, BT, Message Number, NNNN.");
  }
  return variables;
}

const canonicalJson = (value: unknown): string => JSON.stringify(value, (_key, item) => item && typeof item === "object" && !Array.isArray(item) ? Object.fromEntries(Object.entries(item).sort(([a], [b]) => a.localeCompare(b))) : item);

/** The message type a template drafts: its name, in upper case. */
export const templateType = (name: string) => name.trim().replace(/\s+/g, " ").toUpperCase();

/** New publications require the standard contract; old versions are not rewritten. */
export function validateTemplateForPublication(value: unknown): TemplateDefinition {
  const definition = validateTemplateDefinition(value);
  const topic = definition.fields.find((field) => field.name === "Type");
  if (!topic) invalid('Every template must include {{ Type }} (case-sensitive).');
  // The template's name is its message type: one template drafts one type, and
  // the name is written in MSGID field 2 (SAFETY or SAFETY:ELECTRICAL).
  const type = templateType(definition.name);
  if (!/^[A-Z0-9][A-Z0-9 :-]*$/.test(type)) invalid("Name the template after its message type, such as CASREP or SAFETY:ELECTRICAL (letters, digits, spaces, hyphens and one colon).");
  if ((type.match(/:/g) ?? []).length > 1) invalid("A message type has at most one colon, between the type and its subtag.");
  definition.fields = definition.fields.map((field) => field.name === "Type" ? { ...field, fixedValue: type } : field);
  validateStandardTemplateText(definition.text);
  for (const name of STANDARD_FIELD_NAMES) {
    const field = definition.fields.find((item) => item.name === name);
    if (canonicalJson(field) !== canonicalJson(standardField(name))) invalid(`${name} must use the standard template configuration; its behavior cannot be changed.`);
  }
  return definition;
}

export function compileTemplate(definition: TemplateDefinition) {
  // Only user-entered values belong in the client input schema. With
  // additionalProperties:false, a supplied autogenerated value is invalid.
  const manualFields = definition.fields.filter((field) => field.control !== "autogenerated" && field.fixedValue === undefined && !isDraftManagedField(field));
  const properties = Object.fromEntries(manualFields.map((field) => {
    let schema: Record<string, unknown> = { type: "string", maxLength: 5000 };
    if (field.required) schema.minLength = 1;
    if (field.control === "checkbox") schema = { type: "boolean", ...(field.required ? { const: true } : {}) };
    if (field.control === "date") schema = { type: "string", format: "date" };
    // Keep the historical control identifier, but new definitions require an
    // explicit 24-hour Zulu value rather than a browser-local wall-clock time.
    if (field.control === "datetime-local") schema = { type: "string", pattern: ZULU_DATETIME_PATTERN };
    if (["select", "radio"].includes(field.control)) schema = { type: "string", enum: field.options };
    if (field.control === "checkbox-group") schema = { type: "array", uniqueItems: true, items: { type: "string", enum: field.options }, ...(field.required ? { minItems: 1 } : {}) };
    if (field.control === "command-single") schema = { type: "string", format: "uuid" };
    if (field.control === "command-multiple") schema = { type: "array", uniqueItems: true, items: { type: "string", format: "uuid" }, ...(field.required ? { minItems: 1 } : {}) };
    // A JSON list of references, kept as one string so a draft's values stay flat.
    if (field.control === "reference-list") schema = { type: "string", maxLength: MAX_REFERENCE_VALUE, contentMediaType: "application/json" };
    return [field.name, schema];
  }));
  return {
    inputSchema: { $schema: "https://json-schema.org/draft/2020-12/schema", type: "object", additionalProperties: false, properties, required: manualFields.filter((field) => field.required).map((field) => field.name) },
    uiSchema: { fields: definition.fields.map((field) => ({ ...field, ...(isCommandChoice(field.control) ? { reference: { source: "recipient-commands", contractVersion: 1, parameters: {} } } : field.control === "reference-list" ? { reference: { source: "local-messages", contractVersion: 1, parameters: {} } } : {}) })) },
    outputDefinition: { format: "plaintext", body: definition.text, placeholderSyntax: "named-v1" },
  };
}

// Apply the message-output policy after substitution, including command names
// and automatic values. Preview and persistence must use this same entry point.
export function renderGeneratedMessage(text: string, values: TemplateValues, fields: readonly TemplateField[] = [], maxOutputLength = Infinity): string {
  const output = wrapMessageText(renderTemplatePreview(text, values, fields, maxOutputLength));
  if (output.length > maxOutputLength) throw new TemplateValidationError("Generated message is too large after line wrapping.");
  return output;
}

// One pass only: inserted values are never evaluated as template source or HTML.
export function renderTemplatePreview(text: string, values: TemplateValues, fields: readonly TemplateField[] = [], maxOutputLength = Infinity): string {
  let outputLength = text.length;
  const configurations = new Map(fields.map((field) => [field.name, field]));
  const zuluDateTime = new RegExp(ZULU_DATETIME_PATTERN);
  const separators = new Map(fields.filter((field) => field.control === "command-multiple").map((field) => [field.name, COMMAND_SEPARATORS.find(({ key }) => key === field.separator)?.value ?? "; "]));
  // A message with no references has no REF line at all: a placeholder alone on
  // its line takes the line with it when the list is empty.
  for (const field of fields) {
    if (field.control !== "reference-list" || !Object.hasOwn(values, field.name) || renderReferenceValue(values[field.name]) !== "") continue;
    const escaped = field.name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    text = text.replace(new RegExp(`^[ \\t]*{{\\s*${escaped}\\s*}}[ \\t]*(?:\\n|$)`, "gm"), "");
  }
  return text.replace(/{{([^{}]*)}}/g, (placeholder, raw: string) => {
    const name = raw.trim();
    const field = configurations.get(name);
    if (field?.fixedValue === undefined && !Object.hasOwn(values, name)) return placeholder;
    const value = field?.fixedValue ?? values[name];
    if (field?.control === "datetime-local" && value && (typeof value !== "string" || !zuluDateTime.test(value))) return placeholder;
    const outputFor = (label: string) => {
      const overrides = field?.optionOutputs;
      return field && (isStaticChoice(field.control) || field.control === "checkbox") && overrides && Object.hasOwn(overrides, label) && overrides[label].trim() ? overrides[label] : label;
    };
    if (field?.control === "reference-list") {
      const lines = renderReferenceValue(value);
      if (lines === null) return placeholder;
      outputLength += lines.length - placeholder.length;
      if (outputLength > maxOutputLength) throw new TemplateValidationError("Generated message is too large. Shorten the references.");
      return lines;
    }
    const output = Array.isArray(value) ? value.map(outputFor).join(separators.get(name) ?? "; ") : typeof value === "boolean" ? outputFor(value ? "YES" : "NO") : outputFor(value);
    outputLength += output.length - placeholder.length;
    if (outputLength > maxOutputLength) throw new TemplateValidationError("Generated message is too large. Shorten the inputs or repeated placeholders.");
    return output;
  });
}
