import type { TemplateField, TemplateValues } from "./message-templates";
import { fmtDate, fmtDateTime } from "./format";

// Stable, versioned identifiers persisted in template definitions. New behavior
// needs a new version; never evaluate template-provided functions or expressions.
export const GENERATED_OUTPUTS = [
  { key: "sending-command", version: 1, label: "Sender command", description: "The directory command of the currently signed-in user." },
  { key: "current-timestamp", version: 2, label: "Current timestamp (Zulu)", description: "24-hour Zulu timestamp, e.g. 24 OCT 2026 1830Z." },
  { key: "current-date", version: 2, label: "Current date (Zulu)", description: "Zulu calendar date, e.g. 24 OCT 2026." },
  { key: "current-dtg", version: 1, label: "Current date-time group (Zulu)", description: "Naval date-time group, e.g. 241830Z OCT 26." },
] as const;
export type GeneratedOutputKey = (typeof GENERATED_OUTPUTS)[number]["key"];
export interface GeneratorBinding { key: GeneratedOutputKey; version: 1 | 2 }
export function defaultGeneratorBinding(key: GeneratedOutputKey): GeneratorBinding {
  return { key, version: GENERATED_OUTPUTS.find((output) => output.key === key)!.version };
}
export const isSupportedGenerator = (key: unknown, version: unknown) => isGeneratedOutputKey(key)
  && (version === 1 || (version === 2 && (key === "current-timestamp" || key === "current-date")));
export interface GenerationContext {
  now: Date;
  sendingCommand?: { id: string; name: string };
  sendingCommandError?: string;
}
export interface GeneratedInputResult {
  values: TemplateValues;
  errors: Record<string, string>;
  resolvedAt: string;
}
export const isGeneratedOutputKey = (key: unknown): key is GeneratedOutputKey => GENERATED_OUTPUTS.some((output) => output.key === key);

// Called by the server with one context per generation. No client input values
// are accepted here; automatic values cannot be overridden by form submissions.
export function resolveGeneratedInputs(fields: TemplateField[], context: GenerationContext): GeneratedInputResult {
  const resolvedAt = context.now.toISOString();
  const values: [string, string][] = [];
  const errors: [string, string][] = [];
  const pad = (value: number) => String(value).padStart(2, "0");
  const months = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"];
  for (const field of fields) {
    if (field.control !== "autogenerated") continue;
    const generator = field.generator;
    if (!generator || !isSupportedGenerator(generator.key, generator.version)) {
      errors.push([field.name, "Unsupported autogenerated output. Create a new template version with a supported generator."]);
      continue;
    }
    switch (generator.key) {
      case "sending-command":
        if (!context.sendingCommand?.name.trim()) errors.push([field.name, context.sendingCommandError || "No sender command is available in the generation context."]);
        else values.push([field.name, context.sendingCommand.name]);
        break;
      // Preserve published version-1 ISO formats (already 24-hour UTC/Z).
      // New bindings use military presentation without changing old definitions.
      case "current-timestamp": values.push([field.name, generator.version === 1 ? resolvedAt : fmtDateTime(context.now)]); break;
      case "current-date": values.push([field.name, generator.version === 1 ? resolvedAt.slice(0, 10) : fmtDate(context.now)]); break;
      case "current-dtg": values.push([field.name, `${pad(context.now.getUTCDate())}${pad(context.now.getUTCHours())}${pad(context.now.getUTCMinutes())}Z ${months[context.now.getUTCMonth()]} ${pad(context.now.getUTCFullYear() % 100)}`]); break;
    }
  }
  return { values: Object.fromEntries(values), errors: Object.fromEntries(errors), resolvedAt };
}
