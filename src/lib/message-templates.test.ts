import assert from "node:assert/strict";
import { test } from "node:test";
import { defaultGeneratorBinding, GENERATED_OUTPUTS, resolveGeneratedInputs } from "./generated-inputs";
import { fmtDateTime, fmtTime, ZULU_DATETIME_PATTERN } from "./format";
import { compileTemplate, extractVariables, INPUT_TYPES, isStaticChoice, renderTemplatePreview, validateTemplateDefinition, type TemplateDefinition } from "./message-templates";

const valid = (): TemplateDefinition => ({
  name: "Readiness report", description: "For local tests", text: "TO {{ Recipients }}\nSUBJ/{{ Subject }}\n{{ Subject }}",
  fields: [
    { name: "Recipients", control: "command-multiple", required: true, options: [] },
    { name: "Subject", control: "text", required: true, options: [] },
  ],
});

test("extracts unique case-sensitive variables in first-occurrence order", () => {
  assert.deepEqual(extractVariables("{{ Name }} {{Name}} {{ name }} {{ Unit-1 }}"), ["Name", "name", "Unit-1"]);
});

test("rejects malformed and executable placeholder syntax", () => {
  for (const text of ["", "no variables", "{{ }}", "{{ Name", "Name }}", "{{{ Name }}}", "{{ a.b }}", "{{#if Name}}", "{{ A\nB }}", "{{ {{ Name }} }}", "{{ __proto__ }}", "{{ Name }}\0"]) {
    assert.throws(() => extractVariables(text), { name: "Error" }, text);
  }
});

test("rejects oversized templates and too many variables", () => {
  assert.throws(() => extractVariables("{{ Name }}" + "x".repeat(50000)));
  assert.throws(() => extractVariables(Array.from({ length: 101 }, (_, index) => `{{ V${index} }}`).join(" ")));
});

test("validates a complete template and normalizes line endings and order", () => {
  const input = valid();
  input.text = input.text.replaceAll("\n", "\r\n");
  input.fields.reverse();
  const parsed = validateTemplateDefinition(input);
  assert.equal(parsed.fields[0].name, "Recipients");
  assert.ok(!parsed.text.includes("\r"));
});

test("rejects missing, extra, duplicate, or unsupported field definitions", () => {
  const base = valid();
  for (const fields of [[], [base.fields[0]], [...base.fields, base.fields[0]], [base.fields[0], base.fields[0]], [{ ...base.fields[0], control: "script" }, base.fields[1]], [{ ...base.fields[0], required: "true" }, base.fields[1]]]) {
    assert.throws(() => validateTemplateDefinition({ ...base, fields }));
  }
});

test("static choices require nonempty unique options; other controls reject options", () => {
  for (const options of [[], [""], ["Same", "Same"], [" One ", "One"]]) {
    assert.throws(() => validateTemplateDefinition({ name: "Choices", description: "", text: "{{ Choice }}", fields: [{ name: "Choice", control: "select", required: false, options }] }));
  }
  const base = valid();
  base.fields[0].options = ["Arbitrary recipient"];
  assert.throws(() => validateTemplateDefinition(base));
});

test("compiles every supported control into a JSON schema and UI definition", () => {
  for (const [control] of INPUT_TYPES) {
    const definition = validateTemplateDefinition({ name: control, description: "", text: "{{ Value }}", fields: [{ name: "Value", control, required: true, options: isStaticChoice(control) ? ["One", "Two"] : [], ...(control === "autogenerated" ? { generator: { key: "current-timestamp", version: 1 } } : {}) }] });
    const compiled = compileTemplate(definition);
    assert.equal(Object.hasOwn(compiled.inputSchema.properties, "Value"), control !== "autogenerated");
    assert.deepEqual(compiled.inputSchema.required, control === "autogenerated" ? [] : ["Value"]);
    assert.equal(compiled.uiSchema.fields[0].control, control);
    assert.equal(compiled.outputDefinition.body, definition.text);
    if (control.startsWith("command-")) assert.equal(compiled.uiSchema.fields[0].reference?.source, "recipient-commands");
  }
});

test("number is not an authorable input type; sender command keeps its stored key", () => {
  assert.ok(!INPUT_TYPES.some(([control]) => String(control) === "number"));
  assert.throws(() => validateTemplateDefinition({ name: "Numbers", description: "", text: "{{ Value }}", fields: [{ name: "Value", control: "number", required: true, options: [] }] }));
  assert.equal(GENERATED_OUTPUTS.find(({ key }) => key === "sending-command")?.label, "Sender command");
});

test("option output overrides preserve labels, input schema and single-pass plaintext rendering", () => {
  for (const control of ["select", "radio", "checkbox-group"] as const) {
    const definition = validateTemplateDefinition({ name: "Choices", description: "", text: "{{ Choice }}", fields: [{ name: "Choice", control, required: true, options: ["Ready", "Not ready"], optionOutputs: { Ready: "  READY {{ Other }}\n", "Not ready": "   " } }] });
    const field = definition.fields[0];
    assert.deepEqual(field.optionOutputs, { Ready: "  READY {{ Other }}\n" });
    const compiled = compileTemplate(definition);
    assert.deepEqual(compiled.uiSchema.fields[0].optionOutputs, field.optionOutputs);
    if (control !== "checkbox-group") assert.deepEqual(compiled.inputSchema.properties.Choice.enum, ["Ready", "Not ready"]);
    const selected = control === "checkbox-group" ? ["Ready", "Not ready"] : "Ready";
    assert.equal(renderTemplatePreview(definition.text, { Choice: selected, Other: "DO NOT EXPAND" }, definition.fields), control === "checkbox-group" ? "  READY {{ Other }}\n; Not ready" : "  READY {{ Other }}\n");
    assert.equal(renderTemplatePreview(definition.text, { Choice: control === "checkbox-group" ? ["Not ready"] : "Not ready" }, definition.fields), "Not ready");
  }
});

test("checkbox states can override YES and NO independently", () => {
  const definition = validateTemplateDefinition({ name: "Checkbox", description: "", text: "{{ Ack }}", fields: [{ name: "Ack", control: "checkbox", required: false, options: [], optionOutputs: { YES: "ACK REQUIRED", NO: "ACK NOT REQUIRED" } }] });
  assert.equal(renderTemplatePreview(definition.text, { Ack: true }, definition.fields), "ACK REQUIRED");
  assert.equal(renderTemplatePreview(definition.text, { Ack: false }, definition.fields), "ACK NOT REQUIRED");
  const field = { ...definition.fields[0], optionOutputs: { YES: "AFFIRM" } };
  assert.equal(renderTemplatePreview(definition.text, { Ack: true }, [field]), "AFFIRM");
  assert.equal(renderTemplatePreview(definition.text, { Ack: false }, [field]), "NO");
  assert.equal(compileTemplate(definition).inputSchema.properties.Ack.type, "boolean");
});

test("output overrides reject invalid options, controls and values", () => {
  const base = { name: "Choice", description: "", text: "{{ Value }}" };
  const field = { name: "Value", control: "select", required: false, options: ["A"] };
  for (const optionOutputs of [null, [], "text", { Unknown: "A" }, { A: 1 }, { A: "\0" }, { A: "x".repeat(5001) }]) {
    assert.throws(() => validateTemplateDefinition({ ...base, fields: [{ ...field, optionOutputs }] }));
  }
  assert.throws(() => validateTemplateDefinition({ ...base, fields: [{ ...field, control: "text", options: [], optionOutputs: {} }] }));
  assert.throws(() => validateTemplateDefinition({ ...base, fields: [{ ...field, control: "checkbox", options: [], optionOutputs: { true: "A" } }] }));
  assert.equal(validateTemplateDefinition({ ...base, fields: [{ ...field, optionOutputs: { A: "" } }] }).fields[0].optionOutputs, undefined);
});

test("multiple-command separators validate and persist without changing input values", () => {
  for (const separator of ["semicolon", "space", "newline"] as const) {
    const input = valid();
    input.fields[0].separator = separator;
    const definition = validateTemplateDefinition(input);
    assert.equal(compileTemplate(definition).uiSchema.fields[0].separator, separator);
    assert.equal(compileTemplate(definition).inputSchema.properties.Recipients.type, "array");
  }
  assert.equal(validateTemplateDefinition(valid()).fields[0].separator, undefined);
  for (const separator of ["comma", "\n", null, 1]) {
    const input = valid();
    assert.throws(() => validateTemplateDefinition({ ...input, fields: [{ ...input.fields[0], separator }, input.fields[1]] }));
  }
  const input = valid();
  assert.throws(() => validateTemplateDefinition({ ...input, fields: [input.fields[0], { ...input.fields[1], separator: "space" }] }));
});

test("command rendering uses per-field separators and preserves existing defaults", () => {
  const fields: TemplateDefinition["fields"] = [
    { name: "TO", control: "command-multiple", required: true, options: [], separator: "semicolon" },
    { name: "INFO", control: "command-multiple", required: false, options: [], separator: "space" },
    { name: "Other", control: "command-multiple", required: false, options: [], separator: "newline" },
    { name: "Categories", control: "checkbox-group", required: false, options: ["A", "B"] },
  ];
  const values = { TO: ["COMMAND A", "COMMAND B"], INFO: ["A", "B"], Other: ["X", "Y"], Categories: ["A", "B"] };
  assert.equal(renderTemplatePreview("{{ TO }}|{{ INFO }}|{{ Other }}|{{ Categories }}|{{ Other }}", values, fields), "COMMAND A; COMMAND B|A B|X\nY|A; B|X\nY");
  assert.equal(renderTemplatePreview("{{ Recipients }}", { Recipients: ["A", "B"] }, valid().fields), "A; B");
  assert.equal(renderTemplatePreview("{{ Other }}", { Other: [] }, fields), "");
  assert.equal(renderTemplatePreview("{{ Other }}", { Other: ["X"] }, fields), "X");
  assert.deepEqual(values.INFO, ["A", "B"]);
});

test("autogenerated fields require allowlisted, versioned bindings", () => {
  const base = { name: "Auto test", description: "", text: "{{ Value }}", fields: [] as unknown[] };
  const field = { name: "Value", control: "autogenerated", required: true, options: [] };
  for (const generator of [undefined, null, "current-timestamp", { key: "eval", version: 1 }, { key: "current-timestamp", version: 3 }, { key: "current-timestamp" }]) {
    assert.throws(() => validateTemplateDefinition({ ...base, fields: [{ ...field, generator }] }));
  }
  const generator = { key: "current-timestamp", version: 1 };
  assert.throws(() => validateTemplateDefinition({ ...base, fields: [{ ...field, generator, options: ["Anything"] }] }));
  assert.throws(() => validateTemplateDefinition({ ...base, fields: [{ ...field, generator, required: false }] }));
  assert.throws(() => validateTemplateDefinition({ ...base, fields: [{ ...field, generator, control: "text" }] }));
});

test("generator configuration is persisted, not resolved at template publication", () => {
  for (const { key } of GENERATED_OUTPUTS) {
    const definition = validateTemplateDefinition({ name: "Generated", description: "", text: "{{ Value }}", fields: [{ name: "Value", control: "autogenerated", required: true, options: [], generator: { key, version: 1 } }] });
    const compiled = compileTemplate(definition);
    assert.deepEqual(compiled.inputSchema.properties, {});
    assert.deepEqual(compiled.inputSchema.required, []);
    assert.equal(compiled.inputSchema.additionalProperties, false);
    assert.deepEqual(compiled.uiSchema.fields[0].generator, { key, version: 1 });
    assert.equal(compiled.outputDefinition.body, "{{ Value }}");
  }
});

test("resolves autogenerated fields from one context and UTC clock", () => {
  const fields = GENERATED_OUTPUTS.map(({ key }) => ({ name: key, control: "autogenerated" as const, required: true, options: [], generator: { key, version: 1 as const } }));
  const result = resolveGeneratedInputs(fields, { now: new Date("2026-10-25T01:30:04.123+07:00"), sendingCommand: { id: "test-command", name: "TEST COMMAND" } });
  assert.deepEqual(result.errors, {});
  assert.deepEqual(result.values, { "sending-command": "TEST COMMAND", "current-timestamp": "2026-10-24T18:30:04.123Z", "current-date": "2026-10-24", "current-dtg": "241830Z OCT 26" });
  assert.equal(result.resolvedAt, result.values["current-timestamp"]);
  assert.equal(renderTemplatePreview("{{ sending-command }} {{ sending-command }}", result.values), "TEST COMMAND TEST COMMAND");
});

test("new autogenerated date/time bindings use military Zulu presentation", () => {
  const fields = GENERATED_OUTPUTS.map(({ key }) => ({ name: key, control: "autogenerated" as const, required: true, options: [], generator: defaultGeneratorBinding(key) }));
  const result = resolveGeneratedInputs(fields, { now: new Date("2026-10-25T01:30:04.123+07:00"), sendingCommand: { id: "test", name: "COMMAND" } });
  assert.equal(result.values["current-timestamp"], "24 OCT 2026 1830Z");
  assert.equal(result.values["current-date"], "24 OCT 2026");
  assert.equal(result.values["current-dtg"], "241830Z OCT 26");
  assert.equal(result.resolvedAt, "2026-10-24T18:30:04.123Z");
  for (const field of fields) {
    const parsed = validateTemplateDefinition({ name: "Generated", description: "", text: `{{ ${field.name} }}`, fields: [field] });
    assert.deepEqual(parsed.fields[0].generator, field.generator);
  }
});

test("military clock displays midnight/noon and validates explicit Zulu inputs", () => {
  assert.equal(fmtTime("2026-10-24T00:05:00Z"), "0005Z");
  assert.equal(fmtTime("2026-10-24T12:30:00Z"), "1230Z");
  assert.equal(fmtDateTime("2026-10-24T23:30:00-03:00"), "25 OCT 2026 0230Z");
  const pattern = new RegExp(ZULU_DATETIME_PATTERN);
  assert.ok(pattern.test("24 OCT 2026 1830Z"));
  for (const value of ["24 OCT 2026 6:30 PM", "24 OCT 2026 1830L", "24 OCT 2026 1830", "24 OCT 2026 2400Z", "24 OCT 2026 1860Z"]) assert.ok(!pattern.test(value));
  const compiled = compileTemplate({ name: "Time", description: "", text: "{{ When }}", fields: [{ name: "When", control: "datetime-local", required: true, options: [] }] });
  assert.equal(compiled.inputSchema.properties.When.pattern, ZULU_DATETIME_PATTERN);
  const fields = [{ name: "When", control: "datetime-local" as const, required: true, options: [] }];
  assert.equal(renderTemplatePreview("{{ When }}", { When: "24 OCT 2026 1830Z" }, fields), "24 OCT 2026 1830Z");
  assert.equal(renderTemplatePreview("{{ When }}", { When: "24 OCT 2026 6:30 PM" }, fields), "{{ When }}");
});

test("missing sending command remains unresolved without breaking time generators", () => {
  const fields = GENERATED_OUTPUTS.map(({ key }) => ({ name: key, control: "autogenerated" as const, required: true, options: [], generator: { key, version: 1 as const } }));
  const result = resolveGeneratedInputs(fields, { now: new Date("2027-01-01T00:00:00Z") });
  assert.ok(result.errors["sending-command"]);
  assert.ok(!Object.hasOwn(result.values, "sending-command"));
  assert.equal(result.values["current-dtg"], "010000Z JAN 27");
  assert.equal(renderTemplatePreview("{{ sending-command }}", result.values), "{{ sending-command }}");
});

test("bounded server rendering stops repeated-placeholder output expansion", () => {
  assert.throws(() => renderTemplatePreview("{{ Value }}".repeat(1000), { Value: "x".repeat(5000) }, [], 1000000), /too large/);
});

test("preview is single-pass plaintext substitution, not code or HTML evaluation", () => {
  assert.equal(renderTemplatePreview("{{ Name }} {{ List }} {{ Flag }} {{ Missing }}", { Name: "{{ Flag }} <b>text</b>", List: ["A", "B"], Flag: false }), "{{ Flag }} <b>text</b> A; B NO {{ Missing }}");
  assert.equal(renderTemplatePreview("{{ constructor }}", {}), "{{ constructor }}");
});
