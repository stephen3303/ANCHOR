import assert from "node:assert/strict";
import { test } from "node:test";
import { compileTemplate, renderGeneratedMessage, validateTemplateDefinition, validateTemplateForPublication, validateStandardTemplateText } from "./message-templates";
import { validateMessageInputs } from "./message-inputs";
import { resolveGeneratedInputs } from "./generated-inputs";
import { newStandardTemplate, prepareTemplateEdit, STANDARD_FIELD_NAMES, STANDARD_TEMPLATE_TEXT, standardField } from "./standard-template";

const definition = () => {
  const result = newStandardTemplate();
  result.name = "  Readiness  Report  ";
  result.fields = result.fields.map((field) => field.name === "Type" ? { ...field, fixedValue: "IGNORED" } : field);
  return result;
};
const topicOf = (value: ReturnType<typeof definition>) => value.fields.find((field) => field.name === "Type")!;

test("publication requires the exact Type placeholder, and the template name is the type", () => {
  const base = definition();
  assert.throws(() => validateTemplateForPublication({ ...base, text: base.text.replace("{{ Type }}", ""), fields: base.fields.filter((field) => field.name !== "Type") }), /Type/);
  for (const name of ["", "   ", "CASREP/1", "A:B:C", "<topic>", ":SAFETY"]) {
    assert.throws(() => validateTemplateForPublication({ ...base, name }), Error, name);
  }
  for (const [name, type] of [["casrep", "CASREP"], ["Safety:Electrical", "SAFETY:ELECTRICAL"], ["OPREP-3", "OPREP-3"]]) {
    assert.equal(topicOf(validateTemplateForPublication({ ...base, name })).fixedValue, type);
  }
  for (const change of [{ control: "textarea" }, { required: false }]) {
    assert.throws(() => validateTemplateForPublication({ ...base, fields: base.fields.map((field) => field.name === "Type" ? { ...field, ...change } : field) }));
  }
});

test("topic is persisted but is not a drafter input; rendering ignores spoofed values", () => {
  const parsed = validateTemplateForPublication(definition());
  assert.equal(topicOf(parsed).fixedValue, "READINESS REPORT");
  const compiled = compileTemplate(parsed);
  assert.equal(compiled.uiSchema.fields.find((field) => field.name === "Type")!.fixedValue, "READINESS REPORT");
  assert.equal(Object.hasOwn(compiled.inputSchema.properties, "Type"), false);
  assert.throws(() => validateMessageInputs(parsed.fields, { Type: "SPOOFED" }));
  assert.ok(renderGeneratedMessage(parsed.text, { Type: "SPOOFED" }, parsed.fields).includes("MSGID/READINESS REPORT/"));
});

test("topic is pinned independently in each version, from that version's name", () => {
  const first = validateTemplateForPublication(definition());
  const next = definition();
  next.name = "SAFETY:ELECTRICAL";
  topicOf(next).fixedValue = "{{ Body }} <topic>";
  const second = validateTemplateForPublication(next);
  assert.equal(topicOf(first).fixedValue, "READINESS REPORT");
  assert.ok(renderGeneratedMessage(second.text, { Body: "Ready" }, second.fields).includes("MSGID/SAFETY:ELECTRICAL/"));
});

test("every standard variable is mandatory and its entire normalized configuration is locked", () => {
  for (const name of STANDARD_FIELD_NAMES) {
    const base = definition();
    const missing = { ...base, text: base.text.replaceAll(`{{ ${name} }}`, ""), fields: base.fields.filter((field) => field.name !== name) };
    assert.throws(() => validateTemplateForPublication(missing), new RegExp(name));
    for (const change of [{ required: false }, { control: "textarea" }, { options: ["Different"] }, { optionOutputs: { YES: "changed" } }, { generator: { key: "current-dtg", version: 1 } }, { separator: "space" }]) {
      // textarea is already the standard Body control, but no mandated field is a textarea.
      assert.throws(() => validateTemplateForPublication({ ...base, fields: base.fields.map((field) => field.name === name ? { ...field, ...change } : field) }), /.+/, `${name}: ${JSON.stringify(change)}`);
    }
  }
  const parsed = validateTemplateForPublication(definition());
  for (const name of STANDARD_FIELD_NAMES) assert.deepEqual(parsed.fields.find((field) => field.name === name), standardField(name));
  assert.equal(standardField("DateTime")!.control, "text", "Keep the standard's manual DateTime behavior");
  assert.equal(standardField("Info")!.required, true);
  assert.equal(standardField("Recipients")!.separator, "newline");
  assert.deepEqual(standardField("Precedence")!.optionOutputs, { "R - Routine": "R", "P - Priority": "P", "O - Immediate": "O", "Z - Flash": "Z" });
});

test("Origin is mandatory, locked to sender command, and cannot be supplied by a drafter", () => {
  const parsed = validateTemplateForPublication(definition());
  const origin = parsed.fields.find((field) => field.name === "Origin")!;
  assert.deepEqual(origin, { name: "Origin", control: "autogenerated", required: true, options: [], generator: { key: "sending-command", version: 1 } });
  assert.equal(Object.hasOwn(compileTemplate(parsed).inputSchema.properties, "Origin"), false);
  assert.deepEqual(validateMessageInputs([origin], {}), {});
  assert.throws(() => validateMessageInputs([origin], { Origin: "SPOOFED" }));
  const generated = resolveGeneratedInputs([origin], { now: new Date("2026-11-05T08:00:00Z"), sendingCommand: { id: "test-command", name: "SESSION COMMAND" } });
  assert.deepEqual(generated.values, { Origin: "SESSION COMMAND" });
  const text = renderGeneratedMessage(parsed.text, generated.values, parsed.fields);
  assert.ok(text.includes("FM SESSION COMMAND\n"));
  assert.ok(text.includes("MSGID/READINESS REPORT/SESSION COMMAND//"));
  assert.equal(resolveGeneratedInputs([origin], { now: new Date() }).errors.Origin, "No sender command is available in the generation context.");
});

test("requires exactly two literal standalone BT lines and a final NNNN, in standard field order", () => {
  for (const text of [
    STANDARD_TEMPLATE_TEXT.replace("\nBT\n", "\n"),
    STANDARD_TEMPLATE_TEXT.replace("\nBT\n", "\n{{ Break }}\n"),
    STANDARD_TEMPLATE_TEXT.replace("\nBT\n", "\nBT BT\n"),
    STANDARD_TEMPLATE_TEXT.replace("\nBT\n", "\n BT\n"),
    `BT\n${STANDARD_TEMPLATE_TEXT}`,
    STANDARD_TEMPLATE_TEXT.replace("NNNN", "nnnn"),
    `${STANDARD_TEMPLATE_TEXT}\nExtra`,
    STANDARD_TEMPLATE_TEXT.replace("{{ Message Number }}", "").replace("{{ POC }}", "{{ POC }} {{ Message Number }}"),
    STANDARD_TEMPLATE_TEXT.replace("{{ DateTime }}", "{{ Classification }}").replace("{{ Classification }}//", "{{ DateTime }}//"),
  ]) assert.throws(() => validateStandardTemplateText(text));
  assert.doesNotThrow(() => validateStandardTemplateText(STANDARD_TEMPLATE_TEXT.replaceAll("\n", "\r\n") + "\n"));
});

test("new templates are isolated copies of the standard source, without a TODO header and with the standard Body", () => {
  const first = newStandardTemplate();
  const second = newStandardTemplate();
  first.fields[0].options.push("Injected");
  assert.ok(!second.fields[0].options.includes("Injected"));
  assert.ok(second.text.startsWith("{{ Precedence }} {{ DateTime }}\n"));
  assert.ok(!second.text.includes("TODO: figure out header"));
  assert.equal(second.fields.find((field) => field.name === "Body")!.control, "textarea");
  assert.deepEqual(validateStandardTemplateText(second.text), second.fields.map((field) => field.name));
});

test("editing renames legacy variables and restores locked controls only in the editable copy", () => {
  const base = definition();
  const legacyNames: Record<string, string> = { Type: "Msg Type", Origin: "Origin Command", DateTime: "Message DateTime", Recipients: "Recipient Commands", Info: "Info Commands", POC: "Point of Contact" };
  const legacy = { ...base,
    text: base.text.replace(/{{([^{}]*)}}/g, (placeholder, raw: string) => legacyNames[raw.trim()] ? `{{ ${legacyNames[raw.trim()]} }}` : placeholder),
    fields: base.fields.map((field) => ({ ...field, name: legacyNames[field.name] ?? field.name })),
  };
  const snapshot = structuredClone(legacy);
  assert.doesNotThrow(() => validateTemplateDefinition(legacy));
  assert.throws(() => validateTemplateForPublication(legacy));
  assert.deepEqual(validateTemplateForPublication(prepareTemplateEdit(legacy)), validateTemplateForPublication(base));
  assert.deepEqual(legacy, snapshot);
  const collision = { ...legacy, text: `${legacy.text}\n{{ POC }}`, fields: [...legacy.fields, standardField("POC")!] };
  assert.ok(prepareTemplateEdit(collision).fields.some((field) => field.name === "Point of Contact"), "Do not silently merge legacy and new names");
});

test("Originator is renamed to Origin in an editable copy and historical pins are untouched", () => {
  const base = definition();
  const legacy = { ...base, text: base.text.replaceAll("{{ Origin }}", "{{ Originator }}"), fields: base.fields.map((field) => field.name === "Origin" ? { ...field, name: "Originator" } : field) };
  const snapshot = structuredClone(legacy);
  assert.doesNotThrow(() => validateTemplateDefinition(legacy));
  assert.throws(() => validateTemplateForPublication(legacy), /Origin/);
  assert.deepEqual(validateTemplateForPublication(prepareTemplateEdit(legacy)), validateTemplateForPublication(base));
  assert.deepEqual(legacy, snapshot);
});

test("legacy pinned templates still validate and render without new publication requirements", () => {
  const legacy = { name: "Legacy", description: "", text: "{{ Body }}", fields: [{ name: "Body", control: "textarea" as const, required: true, options: [] }] };
  const parsed = validateTemplateDefinition(legacy);
  assert.equal(renderGeneratedMessage(parsed.text, { Body: "Unchanged" }, parsed.fields), "Unchanged");
  assert.throws(() => validateTemplateForPublication(legacy), /Type/);
});
