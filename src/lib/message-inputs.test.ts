import assert from "node:assert/strict";
import { test } from "node:test";
import { validateMessageInputs, MessageInputError } from "./message-inputs";
import type { TemplateField } from "./message-templates";
const field = (control: TemplateField["control"], required = true): TemplateField => ({ name: "Value", control, required, options: ["Ready", "Not ready"].filter(() => ["select", "radio", "checkbox-group"].includes(control)) });

test("required and optional text inputs are validated without changing their content", () => {
  assert.throws(() => validateMessageInputs([field("text")], {}), MessageInputError);
  assert.throws(() => validateMessageInputs([field("text")], { Value: "  " }));
  assert.throws(() => validateMessageInputs([field("text")], { Value: 42 }));
  assert.throws(() => validateMessageInputs([field("text")], { Value: "a".repeat(5001) }));
  assert.deepEqual(validateMessageInputs([field("textarea")], { Value: "  TEST\nTEXT  " }), { Value: "  TEST\nTEXT  " });
  assert.deepEqual(validateMessageInputs([field("text", false)], {}), { Value: "" });
});
test("choices validate original labels, not output overrides", () => {
  for (const control of ["select", "radio", "checkbox-group"] as const) {
    const configuration = { ...field(control), optionOutputs: { Ready: "READY OUTPUT" } };
    assert.throws(() => validateMessageInputs([configuration], { Value: control === "checkbox-group" ? ["READY OUTPUT"] : "READY OUTPUT" }));
    assert.deepEqual(validateMessageInputs([configuration], { Value: control === "checkbox-group" ? ["Ready"] : "Ready" }).Value, control === "checkbox-group" ? ["Ready"] : "Ready");
  }
  assert.throws(() => validateMessageInputs([field("checkbox-group")], { Value: ["Ready", "Ready"] }));
  assert.throws(() => validateMessageInputs([field("checkbox-group")], { Value: [] }));
  assert.deepEqual(validateMessageInputs([field("checkbox-group", false)], {}), { Value: [] });
});
test("checkboxes accept booleans and enforce required checked states", () => {
  assert.throws(() => validateMessageInputs([field("checkbox")], { Value: false }));
  assert.throws(() => validateMessageInputs([field("checkbox")], { Value: "YES" }));
  assert.deepEqual(validateMessageInputs([field("checkbox", false)], {}), { Value: false });
});
test("command fields submit unique directory IDs, not freeform names", () => {
  const id = "abcdefab-cdef-4abc-8def-abcdefabcdef";
  assert.deepEqual(validateMessageInputs([field("command-multiple")], { Value: [id] }), { Value: [id] });
  assert.throws(() => validateMessageInputs([field("command-single")], { Value: "COMSUBLANT NORFOLK VA" }));
  assert.throws(() => validateMessageInputs([field("command-multiple")], { Value: [id, id.toUpperCase()] }));
  assert.deepEqual(validateMessageInputs([field("command-single")], { Value: id.toUpperCase() }), { Value: id });
  assert.deepEqual(validateMessageInputs([field("command-single", false)], {}), { Value: "" });
});
test("server-generated and unknown fields cannot be submitted", () => {
  assert.throws(() => validateMessageInputs([field("text")], { Value: "Text", Unknown: "spoof" }));
  assert.throws(() => validateMessageInputs([field("autogenerated")], { Value: "spoof" }));
  assert.deepEqual(validateMessageInputs([field("autogenerated")], {}), {});
});
test("date and military date/time inputs validate real calendar days", () => {
  assert.deepEqual(validateMessageInputs([field("date")], { Value: "2028-02-29" }), { Value: "2028-02-29" });
  for (const Value of ["2026-02-29", "2026-02-31", "2026-13-01"]) assert.throws(() => validateMessageInputs([field("date")], { Value }));
  assert.deepEqual(validateMessageInputs([field("datetime-local")], { Value: "24 OCT 2026 1830Z" }), { Value: "24 OCT 2026 1830Z" });
  for (const Value of ["31 FEB 2026 1830Z", "24 OCT 2026 6:30 PM", "24 OCT 2026 1830L", "24 OCT 2026 2400Z"]) assert.throws(() => validateMessageInputs([field("datetime-local")], { Value }));
});
